from PySide6.QtCore import Signal
from PySide6.QtWidgets import QWidget, QVBoxLayout, QLabel, QComboBox, QCheckBox, QSlider, QFormLayout, QFrame
from PySide6.QtCore import Qt


class SettingsPanel(QWidget):
    changed = Signal(str, object)

    def __init__(self, settings, voice_panel, camera_panel, parent=None):
        super().__init__(parent)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(0, 0, 0, 0)
        title = QLabel('Налаштуйте асистента під себе')
        title.setObjectName('sectionTitle')
        layout.addWidget(title)
        form = QFormLayout()
        form.setVerticalSpacing(22)
        self.language = QComboBox()
        self.language.addItem('Російська', 'ru')
        self.language.addItem('Англійська', 'en')
        self.language.setCurrentIndex(max(0, self.language.findData(settings.get('language', 'ru'))))
        form.addRow('Мова розпізнавання', self.language)
        self.model_status = QLabel()
        self.model_status.setWordWrap(True)
        form.addRow('Офлайн-модель', self.model_status)
        form.addRow('Мікрофон', voice_panel.device_combo)
        form.addRow('', voice_panel.refresh_button)
        form.addRow('Номер камери', camera_panel.device_index)
        self.wake_required = QCheckBox('Виконувати команду лише після звернення')
        self.wake_required.setChecked(settings.get('wake_required', True))
        form.addRow('Активація', self.wake_required)
        self.animations = QCheckBox('Анімувати ядро та індикатори')
        self.animations.setChecked(settings.get('animations', True))
        form.addRow('Анімації', self.animations)
        self.smoothing = QSlider(Qt.Horizontal)
        self.smoothing.setRange(5, 100)
        self.smoothing.setTracking(False)
        self.smoothing.setValue(round(settings.get('smoothing', .25)*100))
        self.smoothing.setToolTip('Менше значення — плавніший рух; більше — швидша реакція.')
        form.addRow('Реакція курсора', self.smoothing)
        self.sensitivity = QSlider(Qt.Horizontal)
        self.sensitivity.setRange(25, 200)
        self.sensitivity.setTracking(False)
        self.sensitivity.setValue(round(settings.get('sensitivity', 1.0)*100))
        self.sensitivity.setToolTip('Чутливість розпізнавання щипка: менше — точніший жест; більше — легше натиснути.')
        form.addRow('Чутливість жестів', self.sensitivity)
        layout.addLayout(form)
        self.message = QLabel(getattr(settings, 'error', ''))
        self.message.setWordWrap(True)
        layout.addWidget(self.message)
        layout.addStretch()
        foot = QLabel('Усі розпізнавання виконуються на цьому комп’ютері.\nКерування жестами потрібно дозволяти вручну після кожного запуску.')
        foot.setObjectName('pageSubtitle')
        foot.setWordWrap(True)
        layout.addWidget(foot)
        self.language.currentIndexChanged.connect(lambda: self.changed.emit('language', self.language.currentData()))
        self.wake_required.toggled.connect(lambda value: self.changed.emit('wake_required', value))
        self.animations.toggled.connect(lambda value: self.changed.emit('animations', value))
        self.smoothing.valueChanged.connect(lambda value: self.changed.emit('smoothing', value/100))
        self.sensitivity.valueChanged.connect(lambda value: self.changed.emit('sensitivity', value/100))
        voice_panel.device_combo.activated.connect(lambda: self.changed.emit('microphone', voice_panel.device_combo.currentData()))
        camera_panel.device_index.valueChanged.connect(lambda value: self.changed.emit('camera', value))
